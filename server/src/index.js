import dotenv from "dotenv";
import {fileURLToPath} from "node:url";
dotenv.config({path:fileURLToPath(new URL("../../.env",import.meta.url))});
import express from "express";
import cors from "cors";
import helmet from "helmet";
import morgan from "morgan";
import {connectDB} from "./config/db.js";
import api from "./routes/api.js";
import auth from "./routes/auth.js";
import code from "./routes/code.js";
import {requireAuth} from "./middleware/auth.js";
const app=express();
app.disable("x-powered-by");
app.use(helmet());
app.use(cors({origin:process.env.CLIENT_ORIGIN||"http://localhost:5173"}));
app.use(express.json({limit:"350kb"}));
app.use(morgan("dev"));
app.get("/",(_req,res)=>res.json({name:"TERMINUS API",health:"/api/health",documentation:"See README.md"}));
app.use("/api/auth",auth);
app.use("/api/code",requireAuth,code);
app.use("/api",api);
app.use((err,_req,res,_next)=>{console.error(err);res.status(500).json({message:"Internal server error"});});
const port=Number(process.env.PORT)||5000;
connectDB(process.env.MONGODB_URI).then(()=>app.listen(port,()=>console.log("TERMINUS API listening on http://localhost:"+port))).catch(error=>{console.error("MongoDB connection failed:",error.message);process.exit(1);});
